import { useState } from "react";

import { api, ApiError } from "../api";
import { formatDateTime } from "../format";
import { CheckIcon, EyeIcon } from "../icons";
import type { AIStatus, Diagnosis } from "../types";
import { usePolling } from "../usePolling";
import { ConfidenceBadge } from "./Badges";

/**
 * Optional AI assistance. Observed facts (computed by the backend from stored data) and
 * AI-generated hypotheses are shown apart, so generated text never passes for a fact.
 * The AI is only called on an explicit click; reading a stored diagnosis is free.
 */
export function DiagnosisPanel({ incidentId, ai }: { incidentId: string; ai: AIStatus | null }) {
  // Stored diagnoses do not change on their own: load once, no polling needed.
  const stored = usePolling((signal) => api.diagnosis(incidentId, signal), 3_600_000, [incidentId]);
  const [fresh, setFresh] = useState<Diagnosis | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const diagnosis = fresh ?? stored.data;

  async function analyze() {
    setBusy(true);
    setError(null);
    try {
      setFresh(await api.requestDiagnosis(incidentId));
    } catch (reason) {
      // 429 quota, 504 timeout, 502 provider error, 503 not configured: all have a message.
      setError(reason instanceof ApiError ? reason.message : "The AI diagnosis failed.");
    } finally {
      setBusy(false);
    }
  }

  return (
    <section className="card ai-panel" aria-labelledby="ai-title">
      <div className="card-header">
        <h2 id="ai-title">AI assistant</h2>
        {ai?.enabled && (
          <button type="button" className="btn ai" disabled={busy} onClick={analyze}>
            {busy ? "Analyzing…" : diagnosis ? "Regenerate" : "Analyze with AI"}
          </button>
        )}
      </div>

      {ai && !ai.enabled && (
        <p className="muted">
          AI diagnosis is off: no <code>GEMINI_API_KEY</code> is configured on the server. Everything
          else works without it.
        </p>
      )}
      {ai?.enabled && !diagnosis && !busy && !error && (
        <p className="muted">
          Get hypotheses and suggested checks for this incident. Only this incident and its
          service&apos;s simulated metrics are sent to {ai.provider} ({ai.model}).
        </p>
      )}
      {busy && <p className="muted">Asking {ai?.model}… this can take a few seconds.</p>}
      {error && (
        <div className="alert" role="alert">
          {error}
        </div>
      )}

      {diagnosis && (
        <div className="ai-result">
          <div className="ai-block">
            <h3>
              <EyeIcon /> Observed facts <span className="muted small">computed from stored data</span>
            </h3>
            <ul className="facts-list">
              {diagnosis.facts.map((fact) => (
                <li key={fact}>{fact}</li>
              ))}
            </ul>
          </div>

          <div className="ai-block generated">
            <h3>
              <span className="ai-mark" aria-hidden="true" /> Hypotheses <span className="muted small">AI-generated · not confirmed</span>
            </h3>
            <p>{diagnosis.summary}</p>
            {diagnosis.hypotheses.map((h) => (
              <div key={h.title} className="hypothesis">
                <div className="hypothesis-title">
                  <strong>{h.title}</strong> <ConfidenceBadge confidence={h.confidence} />
                </div>
                <p className="secondary">{h.reasoning}</p>
                {h.supporting_facts.length > 0 && (
                  <ul className="small muted">
                    {h.supporting_facts.map((f) => (
                      <li key={f}>{f}</li>
                    ))}
                  </ul>
                )}
              </div>
            ))}
          </div>

          <div className="ai-block">
            <h3>
              <CheckIcon /> Suggested checks
            </h3>
            <ul className="checks">
              {diagnosis.suggested_checks.map((check) => (
                <li key={check}>{check}</li>
              ))}
            </ul>
          </div>

          <p className="disclaimer small">
            {diagnosis.disclaimer} Generated by {diagnosis.model} on {formatDateTime(diagnosis.created_at)}.
          </p>
        </div>
      )}
    </section>
  );
}
